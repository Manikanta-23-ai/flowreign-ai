
import re


def build_plan(objective: str, requires_approval: bool = True) -> dict:
    """
    Create a deterministic task plan from a business objective.

    This is a rule-based MVP planner, not an LLM-powered agent.
    """

    text = objective.strip()
    if len(text) < 5:
        raise ValueError("Objective must contain at least 5 characters.")

    lower = text.lower()

    research_keywords = (
        "research", "competitor", "market", "customer",
        "feedback", "industry", "survey",
    )
    data_keywords = (
        "data", "dataset", "sales", "revenue", "analytics",
        "analysis", "performance", "metrics",
    )
    automation_keywords = (
        "automate", "automation", "workflow", "email",
        "reporting", "schedule", "integration",
    )

    tasks = []

    def add_task(task_id, title, agent, description, depends_on=None):
        tasks.append({
            "task_id": task_id,
            "title": title,
            "assigned_agent": agent,
            "description": description,
            "depends_on": depends_on or [],
            "status": "planned",
            "requires_human_approval": requires_approval,
        })

    add_task(
        "task-01",
        "Understand the objective",
        "Planning Agent",
        f"Identify the desired outcome, constraints, and deliverables "
        f"for: {text}",
    )

    if any(word in lower for word in research_keywords):
        research_description = (
            "Gather relevant information and record sources, "
            "evidence, and unresolved questions."
        )
    else:
        research_description = (
            "Identify the information, resources, and evidence "
            "needed to complete the objective."
        )

    add_task(
        "task-02",
        "Research and gather evidence",
        "Research Agent",
        research_description,
        ["task-01"],
    )

    if any(word in lower for word in data_keywords):
        analysis_description = (
            "Inspect available data, validate its quality, "
            "calculate relevant metrics, and identify patterns."
        )
        analysis_agent = "Data Analyst Agent"
    elif any(word in lower for word in automation_keywords):
        analysis_description = (
            "Map the process, identify repetitive steps, "
            "and define automation opportunities."
        )
        analysis_agent = "Automation Analyst Agent"
    else:
        analysis_description = (
            "Evaluate the gathered information, identify insights, "
            "and develop evidence-based recommendations."
        )
        analysis_agent = "Analysis Agent"

    add_task(
        "task-03",
        "Analyze findings",
        analysis_agent,
        analysis_description,
        ["task-02"],
    )

    add_task(
        "task-04",
        "Prepare the deliverable",
        "Report Generation Agent",
        "Create a structured output containing findings, "
        "recommendations, supporting evidence, and limitations.",
        ["task-03"],
    )

    add_task(
        "task-05",
        "Quality and evidence review",
        "Quality Assurance Agent",
        "Check completeness, factual consistency, evidence quality, "
        "and whether the deliverable meets the original objective.",
        ["task-04"],
    )

    return {
        "planner": "FlowReign Deterministic Planner v0.1",
        "planning_mode": "rule_based",
        "objective": text,
        "approval_required": requires_approval,
        "total_tasks": len(tasks),
        "tasks": tasks,
        "execution_status": "not_started",
        "notice": (
            "This plan was generated by deterministic rules. "
            "No AI model or external action was executed."
        ),
    }
